#!/usr/bin/env python3
"""Convert the URDF produced by onshape-to-robot into a reusable xacro macro.

Two files are written next to the input URDF ``<stem>.urdf`` (by default). ``<robot>`` is the
URDF's ``<robot name>``, i.e. ``robot_name`` in config.json:

* ``<stem>_macro.xacro`` -- a ``<xacro:macro name="<robot>" params="tf_prefix parent *origin">``
  containing every link/joint of the robot, with ``${tf_prefix}`` prepended to all
  link, joint and material names (and to every reference to them). The robot's root
  link is attached to ``${parent}`` through a fixed ``${tf_prefix}base_joint`` whose
  origin is the ``*origin`` block, following the Universal Robots convention.
* ``<stem>.urdf.xacro`` -- a top-level description that defines a dummy ``world`` link
  and instantiates the macro on it. This is what ``robot_state_publisher`` should load.

The plain URDF is left untouched so it can still be used by non-ROS tools (MuJoCo, etc.).
Joint limits, efforts and velocities are copied verbatim: they come from the Onshape
mate limits or from ``joint_properties`` in config.json (see the onshape-to-robot docs).

Only the Python standard library is used, and the output is deterministic: running the
script twice on the same URDF produces byte-identical files.
"""

from __future__ import annotations

import argparse
import keyword
import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

XACRO_NS = "http://www.ros.org/wiki/xacro"
PREFIX = "${tf_prefix}"
ATTACH_JOINT = "base_joint"
DUMMY_LINK = "world"
# xacro's own directives: a macro with one of these names could never be called.
XACRO_RESERVED = {
    "arg", "attribute", "call", "element", "if", "include", "insert_block", "macro", "property", "unless",
}
GENERATED_NOTE = (
    " Generated by scripts/urdf_to_xacro.py from {source}. Do not edit by hand:"
    " re-run the Update URDF workflow (or the script) instead. "
)

ET.register_namespace("xacro", XACRO_NS)


def xacro(tag: str) -> str:
    return f"{{{XACRO_NS}}}{tag}"


def parse_urdf(path: Path) -> ET.Element:
    parser = ET.XMLParser(target=ET.TreeBuilder(insert_comments=True))
    root = ET.parse(path, parser=parser).getroot()
    if root.tag != "robot":
        raise ValueError(f"{path}: root element is <{root.tag}>, expected <robot>")
    return root


def escape_dollars(robot: ET.Element) -> None:
    """Make ``${`` and ``$(`` in the source URDF literal for xacro (``$${`` / ``$$(``).

    Otherwise text such as ``$(HOME)`` coming from config.json's additional_xml would be
    evaluated (or fail) when the macro is expanded. Comments are not evaluated by xacro.
    """

    def escape(value: str) -> str:
        return value.replace("${", "$${").replace("$(", "$$(")

    for element in robot.iter():
        if element.tag is ET.Comment:
            continue
        for key, value in element.attrib.items():
            element.set(key, escape(value))
        if element.text:
            element.text = escape(element.text)
        if element.tail:
            element.tail = escape(element.tail)


def check_macro_name(name: str) -> None:
    if not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", name) or name in XACRO_RESERVED or keyword.iskeyword(name):
        raise ValueError(
            f"'{name}' cannot be used as a xacro macro name; set \"robot_name\" in config.json to a"
            " name made of letters, digits and underscores that doesn't start with a digit"
            " (or pass --macro-name)"
        )


def find_root_link(robot: ET.Element) -> str:
    links = [link.get("name") for link in robot.findall("link")]
    children = {child.get("link") for child in robot.findall("joint/child")}
    roots = [name for name in links if name not in children]
    if len(roots) != 1:
        raise ValueError(f"expected exactly one root link, found {roots or 'none'}")
    return roots[0]


def strip_dummy_base_link(robot: ET.Element, root_link: str) -> str:
    """Remove the link added by onshape-to-robot's ``add_dummy_base_link`` option.

    The dummy link lives in the top-level .urdf.xacro (as ``world``) instead, so keeping
    onshape-to-robot's one would just add a second massless link. It is recognised by its
    exact signature: a geometry-less ``base_link`` root whose only child joint is the fixed
    ``base_link_to_<link>`` joint created by ProcessorDummyBaseLink.
    """
    if root_link != "base_link":
        return root_link
    link = next(l for l in robot.findall("link") if l.get("name") == "base_link")
    if link.find("visual") is not None or link.find("collision") is not None:
        return root_link
    out_joints = [j for j in robot.findall("joint") if j.find("parent").get("link") == "base_link"]
    if len(out_joints) != 1:
        return root_link
    joint = out_joints[0]
    child = joint.find("child").get("link")
    if joint.get("type") != "fixed" or joint.get("name") != f"base_link_to_{child}":
        return root_link

    # Anything from additional_xml that pointed at the dummy now points at the real root link.
    for gazebo in robot.findall("gazebo"):
        if gazebo.get("reference") == "base_link":
            gazebo.set("reference", child)
            print(f"note: <gazebo reference=\"base_link\"> now refers to '{child}'", file=sys.stderr)

    for element in (link, joint):
        index = list(robot).index(element)
        previous = robot[index - 1] if index > 0 else None
        if previous is not None and previous.tag is ET.Comment:
            robot.remove(previous)  # the "<!-- Link base_link -->"-style comment
        robot.remove(element)
    print(
        "note: removed the dummy base_link added by onshape-to-robot (add_dummy_base_link);"
        " the top-level .urdf.xacro provides the dummy world link instead.",
        file=sys.stderr,
    )
    return child


def prefix_names(robot: ET.Element) -> None:
    """Prepend ${tf_prefix} to every link/joint/material name and every reference to one."""
    link_names = {link.get("name") for link in robot.findall("link")}
    joint_names = {joint.get("name") for joint in robot.findall("joint")}

    def pre(element: ET.Element, attribute: str, known: set[str] | None = None) -> None:
        value = element.get(attribute)
        if value is not None and (known is None or value in known):
            element.set(attribute, PREFIX + value)

    for link in robot.findall("link"):
        pre(link, "name")
    for joint in robot.findall("joint"):
        pre(joint, "name")
        pre(joint.find("parent"), "link")
        pre(joint.find("child"), "link")
        for mimic in joint.findall("mimic"):
            pre(mimic, "joint")

    # Materials are global in URDF: prefix them so two instances can use different colors.
    for material in robot.iter("material"):
        pre(material, "name")

    # Elements that may come from config.json's "additional_xml".
    for gazebo in robot.findall("gazebo"):
        pre(gazebo, "reference", link_names | joint_names)
    for transmission in robot.findall("transmission"):
        pre(transmission, "name")
        for joint in transmission.findall("joint"):
            pre(joint, "name", joint_names)


def check_mesh_uris(robot: ET.Element, package: str) -> None:
    expected = f"package://{package}/"
    for mesh in robot.iter("mesh"):
        filename = mesh.get("filename", "")
        if not filename.startswith(expected):
            print(
                f"warning: mesh '{filename}' does not start with '{expected}'; set"
                f" \"package_name\": \"{package}\" in config.json so meshes resolve.",
                file=sys.stderr,
            )


def build_macro(robot: ET.Element, macro_name: str, root_link: str, source: str) -> ET.Element:
    macro_robot = ET.Element("robot")
    macro_robot.append(ET.Comment(GENERATED_NOTE.format(source=source)))
    macro = ET.SubElement(
        macro_robot, xacro("macro"), {"name": macro_name, "params": "tf_prefix parent *origin"}
    )

    attach = ET.SubElement(macro, "joint", {"name": PREFIX + ATTACH_JOINT, "type": "fixed"})
    ET.SubElement(attach, xacro("insert_block"), {"name": "origin"})
    ET.SubElement(attach, "parent", {"link": "${parent}"})
    ET.SubElement(attach, "child", {"link": PREFIX + root_link})

    for child in list(robot):
        macro.append(child)
    return macro_robot


def build_top_level(macro_name: str, macro_file: str, source: str) -> ET.Element:
    top = ET.Element("robot", {"name": macro_name})
    top.append(ET.Comment(GENERATED_NOTE.format(source=source)))
    ET.SubElement(top, xacro("arg"), {"name": "tf_prefix", "default": ""})
    ET.SubElement(top, xacro("include"), {"filename": macro_file})
    top.append(ET.Comment(" Dummy root link: keeps the robot's first link from being the URDF root. "))
    ET.SubElement(top, "link", {"name": DUMMY_LINK})
    instance = ET.SubElement(
        top, xacro(macro_name), {"tf_prefix": "$(arg tf_prefix)", "parent": DUMMY_LINK}
    )
    ET.SubElement(instance, "origin", {"xyz": "0 0 0", "rpy": "0 0 0"})
    return top


def write(element: ET.Element, path: Path) -> None:
    tree = ET.ElementTree(element)
    ET.indent(tree, space="  ")
    with open(path, "w", encoding="utf-8", newline="\n") as stream:
        stream.write('<?xml version="1.0"?>\n')
        # ElementTree declares xmlns:xacro on the root since xacro:* elements are present.
        stream.write(ET.tostring(element, encoding="unicode"))
        stream.write("\n")


def package_name_from_xml(package_xml: Path) -> str:
    name = ET.parse(package_xml).getroot().findtext("name")
    if not name:
        raise ValueError(f"{package_xml}: missing <name>")
    return name.strip()


def main() -> int:
    repo = Path(__file__).resolve().parent.parent
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("urdf", type=Path, nargs="?", default=repo / "urdf" / "robot.urdf")
    parser.add_argument("-o", "--output-dir", type=Path, help="defaults to the URDF's directory")
    parser.add_argument("--macro-name", help="defaults to the URDF's <robot name>")
    parser.add_argument("--package", help="ROS package name (defaults to <name> in package.xml)")
    args = parser.parse_args()

    robot = parse_urdf(args.urdf)
    macro_name = args.macro_name or robot.get("name")
    check_macro_name(macro_name)
    package = args.package or package_name_from_xml(repo / "package.xml")
    output_dir = args.output_dir or args.urdf.parent
    output_dir.mkdir(parents=True, exist_ok=True)

    root_link = strip_dummy_base_link(robot, find_root_link(robot))
    if ATTACH_JOINT in {joint.get("name") for joint in robot.findall("joint")}:
        raise ValueError(f"the robot already has a joint named '{ATTACH_JOINT}'; rename it in Onshape")
    if DUMMY_LINK in {link.get("name") for link in robot.findall("link")}:
        raise ValueError(
            f"the robot already has a link named '{DUMMY_LINK}' (e.g. from a frame_{DUMMY_LINK} mate),"
            " which would clash with the dummy link of the top-level .urdf.xacro; rename it in Onshape"
        )
    check_mesh_uris(robot, package)
    escape_dollars(robot)
    prefix_names(robot)

    stem = args.urdf.name.removesuffix(".urdf")
    macro_file = output_dir / f"{stem}_macro.xacro"
    top_file = output_dir / f"{stem}.urdf.xacro"
    source = args.urdf.name
    write(build_macro(robot, macro_name, root_link, source), macro_file)
    write(build_top_level(macro_name, macro_file.name, source), top_file)
    print(f"wrote {macro_file} and {top_file}")
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except (ValueError, ET.ParseError, OSError) as error:
        print(f"error: {error}", file=sys.stderr)
        sys.exit(1)
